#!/usr/bin/env python3
"""Create a minimal security/conf config file and patch Makefile to use a hand-crafted valid Makefile."""
import os

# The security/conf config file that doconf would generate
config_content = """# config file for security/conf
# Generated manually to bypass doconf failure

# Build directory
builddir	"."

# Object directory
objectdir	"../../../../../../../BUILD/obj"

# Source directory
sourcedir	"../../../../../../.."

# Standard source files
security/mac_base.c

# MAC framework files (CONFIG_MACF enabled)
security/mac_audit.c
security/mac_data.c
security/mac_label.c
security/mac_necp.c
security/mac_process.c
security/mac_vfs.c
security/mac_vfs_subr.c
security/mac_system.c
security/mac_sysv_sem.c
security/mac_sysv_shm.c
security/mac_sysv_msg.c
security/mac_posix_sem.c
security/mac_posix_shm.c
security/mac_socket.c
security/mac_pipe.c
security/mac_iokit.c
security/mac_file.c
security/mac_priv.c
security/mac_pty.c
security/mac_kext.c
security/mac_mach.c

# Skywalk support
security/mac_skywalk.c
"""

# Ensure directory exists
os.makedirs('security/conf', exist_ok=True)

# Write the config file
with open('security/conf/DEVELOPMENT', 'w') as f:
    f.write(config_content)

print("Created security/conf/DEVELOPMENT config file")

# Create a hand-crafted valid Makefile for security/conf DEVELOPMENT config
# This is based on the security/conf files with CONFIG_MACF enabled
makefile_content = """#
# This Makefile was generated by config
#
# DO NOT EDIT THIS FILE
#

export MakeInc_cmd=${SRCROOT}/makedefs/MakeInc.cmd
export MakeInc_def=${SRCROOT}/makedefs/MakeInc.def
export MakeInc_rule=${SRCROOT}/makedefs/MakeInc.rule
export MakeInc_dir=${SRCROOT}/makedefs/MakeInc.dir

include $(MakeInc_cmd)
include $(MakeInc_def)

#
# XXX: CFLAGS
#
CFLAGS+= -include meta_features.h -DBSD_KERNEL_PRIVATE
SFLAGS+= -include meta_features.h

#
# INCFLAGS to include security prototypes
#
INCFLAGS_MAKEFILE= -I$(SOURCE)/..

#
# Directories for mig generated files
#
COMP_SUBDIRS =

#
#  Make sure we don't remove this by accident if interrupted at the wrong
#  time.
#
.PRECIOUS: Makefile

#
#  Theses macros are filled in by the config program depending on the
#  current configuration.  The MACHDEP macro is replaced by the
#  contents of the machine dependent makefile template and the others
#  are replaced by the corresponding symbol definitions for the
#  configuration.
#

OBJS = \\
	mac_audit.o \\
	mac_base.o \\
	mac_data.o \\
	mac_label.o \\
	mac_necp.o \\
	mac_process.o \\
	mac_vfs.o \\
	mac_vfs_subr.o \\
	mac_system.o \\
	mac_sysv_sem.o \\
	mac_sysv_shm.o \\
	mac_sysv_msg.o \\
	mac_posix_sem.o \\
	mac_posix_shm.o \\
	mac_socket.o \\
	mac_pipe.o \\
	mac_iokit.o \\
	mac_file.o \\
	mac_priv.o \\
	mac_pty.o \\
	mac_kext.o \\
	mac_mach.o \\
	mac_skywalk.o

LIBOBJS =

CFILES = \\
	security/mac_audit.c \\
	security/mac_base.c \\
	security/mac_data.c \\
	security/mac_label.c \\
	security/mac_necp.c \\
	security/mac_process.c \\
	security/mac_vfs.c \\
	security/mac_vfs_subr.c \\
	security/mac_system.c \\
	security/mac_sysv_sem.c \\
	security/mac_sysv_shm.c \\
	security/mac_sysv_msg.c \\
	security/mac_posix_sem.c \\
	security/mac_posix_shm.c \\
	security/mac_socket.c \\
	security/mac_pipe.c \\
	security/mac_iokit.c \\
	security/mac_file.c \\
	security/mac_priv.c \\
	security/mac_pty.c \\
	security/mac_kext.c \\
	security/mac_mach.c \\
	security/mac_skywalk.c

CXXFILES =

SFILES =

MACHDEP =

#
# Diagnostic opt-outs.  We need to make this list empty.
#
# DO NOT ADD MORE HERE.
#
# -Wno-cast-align
mac_base.o_CWARNFLAGS_ADD += -Wno-cast-align
# -Wno-shorten-64-to-32
mac_audit.o_CWARNFLAGS_ADD += -Wno-shorten-64-to-32
mac_base.o_CWARNFLAGS_ADD += -Wno-shorten-64-to-32
mac_process.o_CWARNFLAGS_ADD += -Wno-shorten-64-to-32
# -Wno-sign-conversion
mac_base.o_CWARNFLAGS_ADD += -Wno-sign-conversion
mac_mach.o_CWARNFLAGS_ADD += -Wno-sign-conversion
mac_vfs.o_CWARNFLAGS_ADD += -Wno-sign-conversion
mac_vfs_subr.o_CWARNFLAGS_ADD += -Wno-sign-conversion

# Rebuild if per-file overrides change
${OBJS}: $(firstword $(MAKEFILE_LIST))

# Rebuild if global compile flags change
$(COBJS): .CFLAGS
.CFLAGS: ALWAYS
	$(_v)$(REPLACECONTENTS) $@ $(KCC) $(CFLAGS) $(INCFLAGS)
$(CXXOBJS): .CXXFLAGS
.CXXFLAGS: ALWAYS
	$(_v)$(REPLACECONTENTS) $@ $(KC++) $(CXXFLAGS) $(INCFLAGS)
$(SOBJS): .SFLAGS
.SFLAGS: ALWAYS
	$(_v)$(REPLACECONTENTS) $@ $(S_KCC) $(SFLAGS) $(INCFLAGS)

$(COMPONENT).filelist: $(OBJS)
	@$(LOG_LDFILELIST) "$(COMPONENT)"
	$(_v)for obj in ${OBJS}; do \
		 $(ECHO) $(TARGET)/$(CURRENT_KERNEL_CONFIG)/$${obj}; \
	done > $(COMPONENT).filelist

$(COMPONENT).libfilelist: $(LIBOBJS)
	@$(LOG_LDFILELIST) "lib$(COMPONENT)"
	$(_v)for obj in ${LIBOBJS}; do \
		 $(ECHO) $(TARGET)/$(CURRENT_KERNEL_CONFIG)/$${obj}; \
	done > $(COMPONENT).libfilelist

ifeq ($(RC_ProjectName),xnu_libraries)
do_all: $(COMPONENT).libfilelist
else
do_all: $(COMPONENT).filelist
endif

do_build_all:: do_all

%RULES

include $(MakeInc_rule)
include $(MakeInc_dir)
"""

# Ensure directory exists
os.makedirs('security/conf', exist_ok=True)

# Write the config file
with open('security/conf/DEVELOPMENT', 'w') as f:
    f.write(config_content)

print("Created security/conf/DEVELOPMENT config file")

# Write the hand-crafted Makefile
with open('security/conf/Makefile.valid', 'w') as f:
    f.write(makefile_content)

print("Created security/conf/Makefile.valid")

# Now patch the security/conf Makefile to use the valid Makefile
with open('security/conf/Makefile', 'r') as f:
    content = f.read()

# Replace the doconf rule with a copy of the valid Makefile
old_rule = '''$(TARGET)/$(CURRENT_KERNEL_CONFIG)/Makefile: $(SRCROOT)/SETUP/config/doconf $(OBJROOT)/SETUP/config $(DOCONFDEPS)
	$(_v)$(MKDIR) $(TARGET)/$(CURRENT_KERNEL_CONFIG)
	$(_v)$(SRCROOT)/SETUP/config/doconf -c -cpu $(DOCONF_ARCH_CONFIG_LC) -soc $(CURRENT_MACHINE_CONFIG_LC) -platform $(PLATFORM) -d $(TARGET)/$(CURRENT_KERNEL_CONFIG) -s $(SOURCE) -m $(MASTERCONFDIR) $(DOCONF_SEEF) $(CURRENT_KERNEL_CONFIG)'''

new_rule = '''$(TARGET)/$(CURRENT_KERNEL_CONFIG)/Makefile: $(SOURCE)/Makefile.valid $(SOURCE)/$(CURRENT_KERNEL_CONFIG)
	$(_v)$(MKDIR) $(TARGET)/$(CURRENT_KERNEL_CONFIG)
	$(_v)$(CP) $(SOURCE)/Makefile.valid $(TARGET)/$(CURRENT_KERNEL_CONFIG)/Makefile'''

if old_rule not in content:
    print("WARNING: Could not find doconf rule to replace")
else:
    content = content.replace(old_rule, new_rule)
    with open('security/conf/Makefile', 'w') as f:
        f.write(content)
    print("Patched security/conf/Makefile to use hand-crafted valid Makefile")

print("Done")