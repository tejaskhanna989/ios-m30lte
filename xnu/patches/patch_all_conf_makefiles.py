#!/usr/bin/env python3
"""Generate valid Makefiles for all conf directories and patch component Makefiles to use them.

Bypasses doconf which generates Makefiles with tab issues.
"""
import os
import shutil

components = [
    ('security', 'security/conf'),
    ('bsd', 'bsd/conf'),
    ('osfmk', 'osfmk/conf'),
    ('libkern', 'libkern/conf'),
    ('iokit', 'iokit/conf'),
    ('pexpert', 'pexpert/conf'),
    ('libsa', 'libsa/conf'),
    ('san', 'san/conf'),
]


def parse_files_conf(conf_dir):
    """Parse files.DEVELOPMENT or files to get source file lists."""
    files_path = os.path.join(conf_dir, 'files.DEVELOPMENT')
    if not os.path.exists(files_path):
        files_path = os.path.join(conf_dir, 'files')
    if not os.path.exists(files_path):
        return [], [], []

    cfiles = []
    cxxfiles = []
    sfiles = []

    with open(files_path, 'r') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            parts = line.split()
            filepath = parts[0]

            if filepath.endswith('.c'):
                cfiles.append(filepath)
            elif filepath.endswith('.cpp'):
                cxxfiles.append(filepath)
            elif filepath.endswith('.s'):
                sfiles.append(filepath)

    return cfiles, cxxfiles, sfiles


def generate_conf_makefile(conf_dir, component_name):
    """Generate a proper Makefile for a conf directory with literal tabs."""
    cfiles, cxxfiles, sfiles = parse_files_conf(conf_dir)

    # Build OBJS from CFILES (replace .c with .o)
    objs = [f.replace('.c', '.o') for f in cfiles]
    objs += [f.replace('.cpp', '.o') for f in cxxfiles]
    objs += [f.replace('.s', '.o') for f in sfiles]

    lines = []
    lines.append("#")
    lines.append("# This Makefile was generated by config")
    lines.append("#")
    lines.append("# DO NOT EDIT THIS FILE")
    lines.append("#")
    lines.append("")
    lines.append("export MakeInc_cmd=${SRCROOT}/makedefs/MakeInc.cmd")
    lines.append("export MakeInc_def=${SRCROOT}/makedefs/MakeInc.def")
    lines.append("export MakeInc_rule=${SRCROOT}/makedefs/MakeInc.rule")
    lines.append("export MakeInc_dir=${SRCROOT}/makedefs/MakeInc.dir")
    lines.append("")
    lines.append("include $(MakeInc_cmd)")
    lines.append("include $(MakeInc_def)")
    lines.append("")
    lines.append("#")
    lines.append("# XXX: CFLAGS")
    lines.append("#")
    lines.append("CFLAGS+= -include meta_features.h -DBSD_KERNEL_PRIVATE")
    lines.append("SFLAGS+= -include meta_features.h")
    lines.append("")
    lines.append("#")
    lines.append("# INCFLAGS to include security prototypes")
    lines.append("#")
    lines.append("INCFLAGS_MAKEFILE= -I$(SOURCE)/..")
    lines.append("")
    lines.append("#")
    lines.append("# Directories for mig generated files")
    lines.append("#")
    lines.append("COMP_SUBDIRS =")
    lines.append("")
    lines.append("#")
    lines.append("#  Make sure we don't remove this by accident if interrupted at the wrong")
    lines.append("#  time.")
    lines.append("#")
    lines.append(".PRECIOUS: Makefile")
    lines.append("")
    lines.append("#")
    lines.append("#  Theses macros are filled in by the config program depending on the")
    lines.append("#  current configuration.  The MACHDEP macro is replaced by the")
    lines.append("#  contents of the machine dependent makefile template and the others")
    lines.append("#  are replaced by the corresponding symbol definitions for the")
    lines.append("#  configuration.")
    lines.append("#")
    lines.append("")

    # OBJS
    if objs:
        lines.append("OBJS = \\")
        for obj in objs:
            lines.append("\t" + obj + " \\")
        lines[-1] = lines[-1].rstrip(" \\")
    else:
        lines.append("OBJS =")
    lines.append("")

    # LIBOBJS
    lines.append("LIBOBJS =")
    lines.append("")

    # CFILES
    if cfiles:
        lines.append("CFILES = \\")
        for cf in cfiles:
            lines.append("\t" + cf + " \\")
        lines[-1] = lines[-1].rstrip(" \\")
    else:
        lines.append("CFILES =")
    lines.append("")

    # CXXFILES
    if cxxfiles:
        lines.append("CXXFILES = \\")
        for cf in cxxfiles:
            lines.append("\t" + cf + " \\")
        lines[-1] = lines[-1].rstrip(" \\")
    else:
        lines.append("CXXFILES =")
    lines.append("")

    # SFILES
    if sfiles:
        lines.append("SFILES = \\")
        for sf in sfiles:
            lines.append("\t" + sf + " \\")
        lines[-1] = lines[-1].rstrip(" \\")
    else:
        lines.append("SFILES =")
    lines.append("")

    # MACHDEP
    lines.append("MACHDEP =")
    lines.append("")

    # Diagnostic opt-outs
    lines.append("#")
    lines.append("# Diagnostic opt-outs.  We need to make this list empty.")
    lines.append("#")
    lines.append("# DO NOT ADD MORE HERE.")
    lines.append("#")
    lines.append("# -Wno-cast-align")
    lines.append("# -Wno-shorten-64-to-32")
    lines.append("# -Wno-sign-conversion")
    lines.append("")

    # Rebuild if per-file overrides change
    lines.append("${OBJS}: $(firstword $(MAKEFILE_LIST))")
    lines.append("")

    # Rebuild if global compile flags change
    lines.append("$(COBJS): .CFLAGS")
    lines.append(".CFLAGS: ALWAYS")
    lines.append("\t$(_v)$(REPLACECONTENTS) $@ $(KCC) $(CFLAGS) $(INCFLAGS)")
    lines.append("$(CXXOBJS): .CXXFLAGS")
    lines.append(".CXXFLAGS: ALWAYS")
    lines.append("\t$(_v)$(REPLACECONTENTS) $@ $(KC++) $(CXXFLAGS) $(INCFLAGS)")
    lines.append("$(SOBJS): .SFLAGS")
    lines.append(".SFLAGS: ALWAYS")
    lines.append("\t$(_v)$(REPLACECONTENTS) $@ $(S_KCC) $(SFLAGS) $(INCFLAGS)")
    lines.append("")

    # filelist target
    lines.append("$(COMPONENT).filelist: $(OBJS)")
    lines.append("\t@$(LOG_LDFILELIST) \"$(COMPONENT)\"")
    lines.append("\t$(_v)for obj in ${OBJS}; do \\")
    lines.append("\t\t $(ECHO) $(TARGET)/$(CURRENT_KERNEL_CONFIG)/$${obj}; \\")
    lines.append("\tdone > $(COMPONENT).filelist")
    lines.append("")

    # libfilelist target
    lines.append("$(COMPONENT).libfilelist: $(LIBOBJS)")
    lines.append("\t@$(LOG_LDFILELIST) \"lib$(COMPONENT)\"")
    lines.append("\t$(_v)for obj in ${LIBOBJS}; do \\")
    lines.append("\t\t $(ECHO) $(TARGET)/$(CURRENT_KERNEL_CONFIG)/$${obj}; \\")
    lines.append("\tdone > $(COMPONENT).libfilelist")
    lines.append("")

    # Conditional do_all
    lines.append("ifeq ($(RC_ProjectName),xnu_libraries)")
    lines.append("do_all: $(COMPONENT).libfilelist")
    lines.append("else")
    lines.append("do_all: $(COMPONENT).filelist")
    lines.append("endif")
    lines.append("")

    lines.append("do_build_all:: do_all")
    lines.append("")

    lines.append("%RULES")
    lines.append("")
    lines.append("include $(MakeInc_rule)")
    lines.append("include $(MakeInc_dir)")

    return "\n".join(lines) + "\n"


def patch_component_makefile(component_dir):
    """Patch component Makefile to use pre-generated conf Makefile instead of doconf.

    Adds an override rule at the end of the Makefile. In GNU Make, the last
    rule for a target wins, so this overrides any doconf rule that appeared
    earlier.
    """
    makefile_path = os.path.join(component_dir, 'Makefile')
    if not os.path.exists(makefile_path):
        print(f"WARNING: {makefile_path} not found")
        return False

    conf_dir = os.path.join(component_dir, 'conf')
    conf_name = component_dir

    override_rule = f'''
# Override doconf rule: use pre-generated Makefile instead
$(TARGET)/$(CURRENT_KERNEL_CONFIG)/Makefile: $(SOURCE)/conf/Makefile.valid $(SOURCE)/conf/$(CURRENT_KERNEL_CONFIG)
\t$(_v)$(MKDIR) $(TARGET)/$(CURRENT_KERNEL_CONFIG)
\t$(_v)$(CP) $(SOURCE)/conf/Makefile.valid $(TARGET)/$(CURRENT_KERNEL_CONFIG)/Makefile
'''

    with open(makefile_path, 'r') as f:
        content = f.read()

    # Check if already patched
    if '$(SOURCE)/conf/Makefile.valid' in content:
        print(f"  Already patched {makefile_path}")
        return True

    with open(makefile_path, 'a') as f:
        f.write(override_rule)
    print(f"  Patched {makefile_path}: added override rule for Makefile.valid")
    return True


def main():
    for component, conf_dir in components:
        print(f"\nProcessing {component}/conf...")

        # Generate the conf Makefile
        conf_makefile = generate_conf_makefile(conf_dir, component)
        conf_makefile_path = os.path.join(conf_dir, 'Makefile.valid')
        os.makedirs(conf_dir, exist_ok=True)
        with open(conf_makefile_path, 'w') as f:
            f.write(conf_makefile)
        print(f"  Created {conf_makefile_path} ({len(conf_makefile.split(chr(10)))} lines)")

        # Also create files.DEVELOPMENT if it doesn't exist
        files_dev = os.path.join(conf_dir, 'files.DEVELOPMENT')
        files_plain = os.path.join(conf_dir, 'files')
        if not os.path.exists(files_dev) and os.path.exists(files_plain):
            shutil.copy2(files_plain, files_dev)
            print(f"  Created {files_dev}")

        # Patch the component Makefile
        patch_component_makefile(component)

    print("\nDone")


if __name__ == '__main__':
    main()